#!/bin/sh
# Generate src/b_proto.h: a prototype for every static function defined in
# src/b[1-6]*.c (definitions start with "static" and end with ")" on one line,
# the opening brace on the next line).  Usage: sh tools/protos.sh > src/b_proto.h
cd "$(dirname "$0")/../src" || exit 1
echo '/* b_proto.h - prototypes of all functions (generated by tools/protos.sh) */'
for f in b[1-6]*.c; do
  awk '/^static [^;=]*\)$/ { getline nxt; if (nxt == "{") print $0 ";" }' "$f"
done
