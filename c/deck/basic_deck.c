static int namekind(const char *nme)
{
    long l;
    int sx, li;
    l = (long)strlen(nme);
    if (l > 0 && nme[l - 1] == '(') l--;
    sx = l > 0 ? (unsigned char)nme[l - 1] : 0;
    if (sx == '$') return 2;
    if (sx == '%' || sx == '&') return 1;
    if (sx == '!' || sx == '#') return 0;
    li = l > 0 ? letter_index((unsigned char)nme[0]) : 0;
    if (li >= 1 && li <= 26) return defkind[li];
    return 0;
}

