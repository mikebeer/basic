static void builtin(long id, long base, long na, const char *nme)
{
    double x, y;
    const Str *s;
    const Str *t;
    static Str empty;
    long n, m, p, k, i;
    char nb[96];
    Str tmp;

    x = 0.0;
    s = &empty;
    if (na >= 1) {
        if (argstk[base + 1].t == 0) x = argstk[base + 1].n;
        else s = &argstk[base + 1].s;
    }
    switch (id) {
    case B_ABS:
        if (argok("n", 1, 1, base, na)) rn = fabs(x);
        break;
    case B_SGN:
        if (argok("n", 1, 1, base, na)) {
            if (x > 0) rn = 1.0;
            else if (x < 0) rn = -1.0;
            else rn = 0.0;
        }
        break;
    case B_INT:
        if (argok("n", 1, 1, base, na)) rn = floor(x);
        break;
    case B_FIX:
        if (argok("n", 1, 1, base, na)) rn = d_trunc(x);
        break;
    case B_FRAC:
        if (argok("n", 1, 1, base, na)) rn = x - d_trunc(x);
        break;
    case B_CINT:
    case B_CLNG:
        if (argok("n", 1, 1, base, na)) rn = rint_d(x);
        break;
    case B_CSNG:
    case B_CDBL:
        if (argok("n", 1, 1, base, na)) rn = x;
        break;
    case B_CBOOL:
        if (argok("n", 1, 1, base, na)) {
            if (x != 0) rn = -1.0;
            else rn = 0.0;
        }
        break;
    case B_SQR:
    case B_SQRT:
        if (argok("n", 1, 1, base, na)) {
            if (x < 0) rt_error(5, "Illegal function call");
            else rn = sqrt(x);
        }
        break;
    case B_SIN:
        if (argok("n", 1, 1, base, na)) rn = sin(x);
        break;
    case B_COS:
        if (argok("n", 1, 1, base, na)) rn = cos(x);
        break;
    case B_TAN:
        if (argok("n", 1, 1, base, na)) rn = tan(x);
        break;
    case B_ATN:
    case B_ATAN:
        if (argok("n", 1, 1, base, na)) rn = atan(x);
        break;
    case B_ASIN:
        if (argok("n", 1, 1, base, na)) {
            if (x < -1 || x > 1) rt_error(5, "Illegal function call");
            else rn = asin(x);
        }
        break;
    case B_ACOS:
        if (argok("n", 1, 1, base, na)) {
            if (x < -1 || x > 1) rt_error(5, "Illegal function call");
            else rn = acos(x);
        }
        break;
    case B_ATAN2:
        if (argok("nn", 2, 2, base, na))
            rn = atan2(x, argstk[base + 2].n);
        break;
    case B_SINH:
        if (argok("n", 1, 1, base, na)) rn = sinh(x);
        break;
    case B_COSH:
        if (argok("n", 1, 1, base, na)) rn = cosh(x);
        break;
    case B_TANH:
        if (argok("n", 1, 1, base, na)) rn = tanh(x);
        break;
    case B_EXP:
        if (argok("n", 1, 1, base, na)) {
            if (x > 709) rt_error(6, "Overflow");
            else rn = exp(x);
        }
        break;
    case B_LOG:
        if (argok("n", 1, 1, base, na)) {
            if (x <= 0) rt_error(5, "Illegal function call");
            else rn = log(x);
        }
        break;
    case B_LOG10:
        if (argok("n", 1, 1, base, na)) {
            if (x <= 0) rt_error(5, "Illegal function call");
            else rn = log10(x);
        }
        break;
    case B_LOG2:
        if (argok("n", 1, 1, base, na)) {
            if (x <= 0) rt_error(5, "Illegal function call");
            else rn = log2_d(x);
        }
        break;
    case B_RND:
        if (na == 0) rn = rnd_next();
        else if (argok("n", 1, 1, base, na)) {
            if (x < 0) {
                rnd_state = fmod(rint_d(fabs(x) * 1000.0),
                    2147483646.0) + 1.0;
                rn = rnd_next();
            } else if (x == 0) rn = rnd_last;
            else rn = rnd_next();
        }
        break;
    case B_TIMER:
        rn = clock_seconds();
        break;
    /* ---------- strings ---------- */
    case B_LEN:
        if (argok("s", 1, 1, base, na)) rn = (double)s->n;
        break;
    case B_LEFT:
        if (argok("sn", 2, 2, base, na)) {
            n = tol(argstk[base + 2].n);
            if (n < 0) rt_error(5, "Illegal function call");
            else {
                if (n > s->n) n = s->n;
                rs_text(SP(*s), n);
            }
        }
        break;
    case B_RIGHT:
        if (argok("sn", 2, 2, base, na)) {
            n = tol(argstk[base + 2].n);
            if (n < 0) rt_error(5, "Illegal function call");
            else {
                if (n > s->n) n = s->n;
                rs_text(SP(*s) + s->n - n, n);
            }
        }
        break;
    case B_MID:
        if (argok("snn", 2, 3, base, na)) {
            p = tol(argstk[base + 2].n);
            n = s->n - p + 1;
            if (na == 3) {
                m = tol(argstk[base + 3].n);
                if (m < n) n = m;
            }
            if (p < 1 || n < 0) rt_error(5, "Illegal function call");
            else {
                if (n == 0 || p > s->n) rs_text("", 0);
                else {
                    if (p - 1 + n > s->n) n = s->n - p + 1;
                    rs_text(SP(*s) + p - 1, n);
                }
            }
        }
        break;
    case B_STR:
        if (argok("n", 1, 1, base, na)) {
            fmtnum(x, nb);
            if (x >= 0 && dial == 0) {
                memmove(nb + 1, nb, strlen(nb) + 1);
                nb[0] = ' ';
            }
            rs_text(nb, (long)strlen(nb));
        }
        break;
    case B_VAL:
    case B_VALINT:
    case B_VALLNG:
        if (argok("s", 1, 1, base, na)) {
            rn = valparse(s);
            if (id != B_VAL) rn = d_trunc(rn);
        }
        break;
    case B_CHR:
        if (argok("n", 1, 1, base, na)) {
            n = tol(x);
            if (n < 0 || n > 1114111)
                rt_error(5, "Illegal function call");
            else {
                set_chr(&rs, n);
                rt = 1;
            }
        }
        break;
    case B_ASC:
        if (argok("s", 1, 1, base, na)) {
            if (s->n == 0) rt_error(5, "Illegal function call");
            else rn = (double)(unsigned char)s->p[0];
        }
        break;
    case B_SPACE:
        if (argok("n", 1, 1, base, na)) {
            n = tol(x);
            if (n < 0) rt_error(5, "Illegal function call");
            else if (n > 100000000L) rt_error(7, "Out of memory");
            else {
                s_reserve(&rs, n);
                memset(rs.p, ' ', (size_t)n);
                rs.p[n] = '\0';
                rs.n = n;
                rt = 1;
            }
        }
        break;
    case B_STRING:
        if (argok("n.", 2, 2, base, na)) {
            n = tol(x);
            if (n < 0) rt_error(5, "Illegal function call");
            else {
                char ch;
                ch = ' ';
                if (argstk[base + 2].t == 0) ch = (char)
                    (tol(argstk[base + 2].n) & 255);
                else if (argstk[base + 2].s.n > 0)
                    ch = argstk[base + 2].s.p[0];
                if (n == 0) rs_text("", 0);
                else if (n > 100000000L) rt_error(7, "Out of memory");
                else {
                    s_reserve(&rs, n);
                    memset(rs.p, ch, (size_t)n);
                    rs.p[n] = '\0';
                    rs.n = n;
                    rt = 1;
                }
            }
        }
        break;
    case B_UCASE:
        if (argok("s", 1, 1, base, na)) {
            rs_text(SP(*s), s->n);
            up_str(&rs);
        }
        break;
    case B_LCASE:
        if (argok("s", 1, 1, base, na)) {
            rs_text(SP(*s), s->n);
            for (i = 0; i < rs.n; i++) rs.p[i] = (char)
                to_low((unsigned char)rs.p[i]);
        }
        break;
    case B_LTRIM:
        if (argok("s.", 1, 2, base, na)) {
            strip_into(&rs, SP(*s), s->n, 'L', ' ');
            rt = 1;
        }
        break;
    case B_RTRIM:
        if (argok("s.", 1, 2, base, na)) {
            strip_into(&rs, SP(*s), s->n, 'T', ' ');
            rt = 1;
        }
        break;
    case B_TRIM:
        if (argok("s.", 1, 2, base, na)) {
            strip_into(&rs, SP(*s), s->n, 'B', ' ');
            rt = 1;
        }
        break;
    case B_INSTR:
        if (na == 2 && argok("ss", 2, 2, base, na)) {
            t = &argstk[base + 2].s;
            if (t->n == 0) rn = 1.0;
            else rn = (double)rx_pos(SP(*t), t->n, SP(*s), s->n, 1);
        } else if (na == 3 && argok("nss", 3, 3, base, na)) {
            t = &argstk[base + 2].s;
            s = &argstk[base + 3].s;
            n = tol(x);
            if (n < 1) rt_error(5, "Illegal function call");
            else if (t->n == 0) {
                if (n <= s->n + 1) rn = (double)n;
                else rn = 0.0;
            } else rn = (double)rx_pos(SP(*s), s->n, SP(*t), t->n, n);
        } else if (na < 2 || na > 3)
            rt_error(5, "Illegal function call");
        break;
    case B_INSTRREV:
        if (argok("ss.", 2, 3, base, na)) {
            t = &argstk[base + 2].s;
            if (t->n == 0) rn = (double)(s->n + 1);
            else if (na == 3) {
                n = tol(argstk[base + 3].n);
                if (n < 1) rn = 0.0;
                else rn = (double)rx_lastpos(SP(*t), t->n, SP(*s),
                    s->n, n);
            } else rn = (double)rx_lastpos(SP(*t), t->n, SP(*s), s->n,
                s->n);
        }
        break;
    case B_HEX:
        if (argok("n", 1, 2, base, na)) {
            radixstr(rint_d(x), 4, 16, nb);
            rs_text(nb, (long)strlen(nb));
        }
        break;
    case B_OCT:
        if (argok("n", 1, 2, base, na)) {
            radixstr(rint_d(x), 3, 22, nb);
            rs_text(nb, (long)strlen(nb));
        }
        break;
    case B_BIN:
        if (argok("n", 1, 2, base, na)) {
            char hb[40];
            long hl;
            memset(&tmp, 0, sizeof(tmp));
            radixstr(rint_d(x), 4, 16, hb);
            hl = (long)strlen(hb);
            for (i = 0; i < hl; i++) {
                m = hexval((unsigned char)hb[i]);
                s_catc(&tmp, (m & 8) ? '1' : '0');
                s_catc(&tmp, (m & 4) ? '1' : '0');
                s_catc(&tmp, (m & 2) ? '1' : '0');
                s_catc(&tmp, (m & 1) ? '1' : '0');
            }
            strip_into(&rs, SP(tmp), tmp.n, 'L', '0');
            if (rs.n == 0) s_set(&rs, "0", 1);
            rt = 1;
            s_free(&tmp);
        }
        break;
    case B_SPC:
        if (argok("n", 1, 1, base, na)) {
            n = tol(x);
            if (n < 0) n = 0;
            if (n > 100000000L) rt_error(7, "Out of memory");
            else {
                s_reserve(&rs, n);
                memset(rs.p, ' ', (size_t)n);
                rs.p[n] = '\0';
                rs.n = n;
                rt = 1;
            }
        }
        break;
    case B_TAB:
        if (argok("n", 1, 1, base, na)) {
            n = tol(x) - 1 - out_col;
            if (n < 0) n = 0;
            if (n > 100000000L) rt_error(7, "Out of memory");
            else {
                s_reserve(&rs, n);
                memset(rs.p, ' ', (size_t)n);
                rs.p[n] = '\0';
                rs.n = n;
                rt = 1;
            }
        }
        break;
    case B_POW:
        if (argok("nn", 2, 2, base, na))
            rn = pow(x, argstk[base + 2].n);
        break;
    case B_MAX:
        if (argok("nn", 2, 2, base, na)) {
            rn = x;
            if (argstk[base + 2].n > x) rn = argstk[base + 2].n;
        }
        break;
    case B_MIN:
        if (argok("nn", 2, 2, base, na)) {
            rn = x;
            if (argstk[base + 2].n < x) rn = argstk[base + 2].n;
        }
        break;
    case B_ISNUMERIC:
        if (argok("s", 1, 1, base, na)) {
            y = valparse(s);
            (void)y;
            if (val_ok == 1) rn = -1.0;
            else rn = 0.0;
        }
        break;
    case B_IIF:
        if (argok("n..", 3, 3, base, na)) {
            if (x != 0) k = base + 2;
            else k = base + 3;
            rt = argstk[k].t;
            rn = argstk[k].n;
            s_cpy(&rs, &argstk[k].s);
        }
        break;
    /* ---------- system ---------- */
    case B_DATE:
    case B_TIME: {
        time_t tt;
        struct tm *lt;
        tt = time(NULL);
        lt = localtime(&tt);
        if (lt == NULL) nb[0] = '\0';
        else if (id == B_DATE)
            strftime(nb, sizeof(nb), "%m-%d-%Y", lt);
        else strftime(nb, sizeof(nb), "%H:%M:%S", lt);
        rs_text(nb, (long)strlen(nb));
        break;
    }
    case B_ERR:
        rn = (double)err_code;
        break;
    case B_ERL:
        rn = (double)err_line;
        break;
    case B_FRE:
        rn = 1000000.0;
        break;
    case B_PEEK:
        rn = 0.0;
        break;
    case B_CSRLIN:
        rn = 1.0;
        break;
    case B_POS:
        rn = (double)(out_col + 1);
        break;
    case B_COMMAND:
        if (na == 0) s_cpy(&rs, &cmdline);
        else {
            n = tol(x);
            if (n < 1) s_set(&rs, prog_name, (long)strlen(prog_name));
            else rx_word(&rs, SP(cmdline), cmdline.n, n);
        }
        rt = 1;
        break;
    case B_ENVIRON:
        if (argok("s", 1, 1, base, na)) {
            const char *ev;
            ev = getenv(SP(*s));
            if (ev == NULL) ev = "";
            rs_text(ev, (long)strlen(ev));
        }
        break;
    case B_CURDIR:
        rs_text(".", 1);
        break;
    case B_FREEFILE:
        rn = 0.0;
        for (i = 1; i <= NFILES; i++) {
            if (fl_mode[i] == 0) {
                rn = (double)i;
                break;
            }
        }
        break;
    case B_EOF:
        if (argok("n", 1, 1, base, na)) rn = (double)file_eof(tol(x));
        break;
    case B_LOF:
    case B_LOC:
    case B_SEEK:
        rn = 0.0;
        break;
    case B_INKEY: {
        int c;
        flush_out();
        c = getc(stdin);
        if (c == EOF) rs_text("", 0);
        else {
            char ch;
            ch = (char)c;
            rs_text(&ch, 1);
        }
        break;
    }
    case B_INPUT:
        if (argok("n.", 1, 2, base, na)) {
            FILE *fh;
            int c;
            n = tol(x);
            fh = stdin;
            if (na == 2) {
                k = tol(argstk[base + 2].n);
                if (k < 1 || k > 255 || fl_mode[k] != 1) {
                    rt_error(52, "Bad file number");
                    return;
                }
                fh = fl_fp[k];
            } else flush_out();
            s_clr(&rs);
            for (i = 1; i <= n; i++) {
                c = getc(fh);
                if (c == EOF) {
                    rt_error(62, "Input past end of file");
                    break;
                }
                s_catc(&rs, c);
            }
            rt = 1;
        }
        break;
    default:
        {
            char eb[160];
            strcpy(eb, "Illegal function call (");
            strncat(eb, nme, 60);
            strcat(eb, ")");
            rt_error(5, eb);
        }
        break;
    }
}
