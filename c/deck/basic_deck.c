static void do_subdef(void)
{
    long r;
    /* FUNCTION = value (FreeBASIC result assignment) or a definition
       to skip */
    if (tk[pc + 1].t == 5 && tk[pc + 1].k == 12) {
        if (cfp == 0) {
            syn();
            return;
        }
        r = procs[cf_proc[cfp]].ret;
        pc += 2;
        ex_prec(1);
        if (err_flag == 1) return;
        store_val(r, 0);
        return;
    }
    pc = tk[pc].x;
}

static void do_call(void)
{
    long r;
    pc++;
    if (tk[pc].t != 3 && tk[pc].f == 0) {
        syn();
        return;
    }
    r = find_proc(tk[pc].s);
    if (r == 0) {
        char b[200];
        strcpy(b, "Syntax error: unknown SUB ");
        strncat(b, tk[pc].s, 100);
        rt_error(2, b);
        return;
    }
    pc++;
    call_sub(r);
}

static void do_if(void)
{
    long p, t;
    int c;
    p = pc;
    pc++;
    c = cond_expr();
    if (err_flag == 1) return;
    if (is_kw("THEN")) pc++;
    else if (is_kw("GOTO") == 0) {
        syn();
        return;
    }
    if (tk[p].x == 1) {
        if (c == 0) pc = tk[p].y;
        if (tk[pc].t == 1) goto_tok(pc);
        return;
    }
    t = p;
    for (;;) {
        if (c == 1) break;
        t = tk[t].y;
        if (tks(t, "ELSEIF")) {
            pc = t + 1;
            c = cond_expr();
            if (err_flag == 1) return;
            if (is_kw("THEN")) pc++;
            continue;
        }
        if (tks(t, "ELSE")) pc = t + 1;
        else pc = t;
        break;
    }
}

static void do_gosub(void)
{
    pc++;
    if (gsp > 20000) {
        rt_error(7, "Out of memory");
        return;
    }
    gsp++;
    NEED(g_ret, g_ret_cap, gsp + 2);
    g_ret[gsp] = stmt_end(pc + 1);
    goto_tok(pc);
    if (err_flag == 1) gsp--;
}

static void do_return(void)
{
    long r;
    pc++;
    if (cfp > 0) {
        if (gsp == cf_gsp[cfp]) {
            r = cf_proc[cfp];
            if (procs[r].isfn == 1 && at_end() == 0) {
                ex_prec(1);
                if (err_flag == 1) return;
                store_val(procs[r].ret, 0);
            }
            retflag = 1;
            return;
        }
    }
    if (gsp > 0) {
        pc = g_ret[gsp];
        gsp--;
    } else rt_error(3, "RETURN without GOSUB");
}

static void do_while(void)
{
    long p;
    p = pc;
    pc++;
    if (cond_expr() == 0 && err_flag == 0) pc = tk[p].x;
}

static void do_do(void)
{
    long p;
    int c, isw;
    p = pc;
    pc++;
    if (is_kw("WHILE") || is_kw("UNTIL")) {
        isw = tks(pc, "WHILE");
        pc++;
        c = cond_expr();
        if (err_flag == 1) return;
        if (isw && c == 0) pc = tk[p].x;
        else if (!isw && c == 1) pc = tk[p].x;
    }
}

static void do_loop(void)
{
    long p;
    int c, isw;
    p = pc;
    pc++;
    if (is_kw("WHILE") || is_kw("UNTIL")) {
        isw = tks(pc, "WHILE");
        pc++;
        c = cond_expr();
        if (err_flag == 1) return;
        if (isw && c == 1) pc = tk[p].x;
        else if (!isw && c == 0) pc = tk[p].x;
    } else pc = tk[p].x;
}

static void do_for(void)
{
    long p, slot, j;
    int ok;
    double v, e, st;
    ForEnt *f;
    p = pc;
    pc++;
    lval();
    if (err_flag == 1) return;
    slot = lv_slot;
    if (lv_idx > 0 || vars[slot].kind == 2) {
        rt_error(13, "Type mismatch");
        return;
    }
    need_op(12);
    v = num_expr();
    if (is_kw("TO")) pc++;
    else {
        syn();
        return;
    }
    e = num_expr();
    st = 1.0;
    if (is_kw("STEP")) {
        pc++;
        st = num_expr();
    }
    if (err_flag == 1) return;
    if (vars[slot].kind == 1) v = rint_d(v);
    vars[slot].n = v;
    j = fsp;
    while (j >= 1) {
        if (fstack[j].slot == slot) {
            fsp = j - 1;
            break;
        }
        j--;
    }
    ok = 1;
    if (st >= 0 && v > e) ok = 0;
    if (st < 0 && v < e) ok = 0;
    if (ok == 0) {
        pc = tk[p].x;
        return;
    }
    fsp++;
    NEED(fstack, fstack_cap, fsp + 2);
    f = &fstack[fsp];
    f->slot = slot;
    f->end = e;
    f->step = st;
    f->pc = pc;
    f->forp = p;
}

static void do_next(void)
{
    long slot, j;
    double v;
    int c;
    pc++;
    for (;;) {
        slot = 0;
        if (tk[pc].t == 3) {
            slot = tk[pc].k;
            pc++;
        }
        if (fsp < 1) {
            rt_error(1, "NEXT without FOR");
            return;
        }
        if (slot > 0) {
            j = fsp;
            while (j >= 1) {
                if (fstack[j].slot == slot) break;
                j--;
            }
            if (j < 1) {
                rt_error(1, "NEXT without FOR");
                return;
            }
            fsp = j;
        }
        j = fstack[fsp].slot;
        v = vars[j].n + fstack[fsp].step;
        vars[j].n = v;
        c = 0;
        if (fstack[fsp].step >= 0) {
            if (v <= fstack[fsp].end) c = 1;
        } else {
            if (v >= fstack[fsp].end) c = 1;
        }
        if (c == 1) {
            pc = fstack[fsp].pc;
            return;
        }
        fsp--;
        if (is_op(9)) pc++;
        else break;
    }
}

/* EXIT FOR / CONTINUE FOR */
static void do_exitfor(void)
{
    long f, j;
    int isexit;
    isexit = tks(pc, "EXITFOR");
    f = tk[pc].x;
    j = fsp;
    while (j >= 1) {
        if (fstack[j].forp == f) break;
        j--;
    }
    if (isexit) {
        if (j >= 1) fsp = j - 1;
        pc = tk[f].x;
    } else {
        if (j >= 1) fsp = j;
        pc = tk[f].y;
    }
}

static int cmp3(double an, const Str *as0, int at, double bn,
    const Str *bs, int bt)
{
    if (at != bt) {
        rt_error(13, "Type mismatch");
        return 0;
    }
    if (at == 0) {
        if (an < bn) return -1;
        if (an > bn) return 1;
        return 0;
    }
    return cmp_str(as0, bs);
}

static int case_match(const Str *ss, double sn, int st)
{
    int m, r, c;
    long k;
    double ln;
    Str ls;
    int lt;
    m = 0;
    memset(&ls, 0, sizeof(ls));
    for (;;) {
        r = 0;
        if (is_kw("IS")) {
            pc++;
            k = tk[pc].k;
            if (tk[pc].t != 5 || k < 12 || k > 17) {
                syn();
                s_free(&ls);
                return 0;
            }
            pc++;
            ex_prec(1);
            if (err_flag == 1) {
                s_free(&ls);
                return 0;
            }
            c = cmp3(sn, ss, st, rn, &rs, rt);
            if (k == 12 && c == 0) r = 1;
            else if (k == 13 && c < 0) r = 1;
            else if (k == 14 && c > 0) r = 1;
            else if (k == 15 && c <= 0) r = 1;
            else if (k == 16 && c >= 0) r = 1;
            else if (k == 17 && c != 0) r = 1;
        } else {
            ex_prec(1);
            if (err_flag == 1) {
                s_free(&ls);
                return 0;
            }
            if (is_kw("TO")) {
                pc++;
                ln = rn;
                lt = rt;
                s_cpy(&ls, &rs);
                ex_prec(1);
                if (err_flag == 1) {
                    s_free(&ls);
                    return 0;
                }
                if (cmp3(sn, ss, st, ln, &ls, lt) >= 0
                    && cmp3(sn, ss, st, rn, &rs, rt) <= 0) r = 1;
            } else if (cmp3(sn, ss, st, rn, &rs, rt) == 0) r = 1;
        }
        if (err_flag == 1) {
            s_free(&ls);
            return 0;
        }
        if (r == 1) m = 1;
        if (is_op(9)) pc++;
        else break;
    }
    s_free(&ls);
    return m;
}

static void do_select(void)
{
    long c;
    Str ss;
    double sn;
    int st, m;
    pc++;
    ex_prec(1);
    if (err_flag == 1) return;
    ssp++;
    NEED(sstack, sstack_cap, ssp + 2);
    sstack[ssp].n = rn;
    s_cpy(&sstack[ssp].s, &rs);
    sstack[ssp].t = rt;
    memset(&ss, 0, sizeof(ss));
    s_cpy(&ss, &rs);
    sn = rn;
    st = rt;
    c = tk[stmt_pc].y;
    for (;;) {
        if (tks(c, "ENDSELECT")) {
            pc = c;
            break;
        }
        if (tks(c, "CASEELSE")) {
            pc = c + 1;
            break;
        }
        pc = c + 1;
        m = case_match(&ss, sn, st);
        if (m == 1) break;
        if (err_flag == 1) break;
        c = tk[c].y;
    }
    s_free(&ss);
}

static void do_swap(void)
{
    long s1, i1, s2, i2;
    double an;
    int at;
    Str as0;
    memset(&as0, 0, sizeof(as0));
    pc++;
    lval();
    s1 = lv_slot;
    i1 = lv_idx;
    need_op(9);
    lval();
    s2 = lv_slot;
    i2 = lv_idx;
    if (err_flag == 1) return;
    load_val(s1, i1);
    an = rn;
    at = rt;
    s_cpy(&as0, &rs);
    load_val(s2, i2);
    store_val(s1, i1);
    if (err_flag == 1) {
        s_free(&as0);
        return;
    }
    rn = an;
    s_cpy(&rs, &as0);
    rt = at;
    store_val(s2, i2);
    s_free(&as0);
}

static void do_on(void)
{
    static long *tp;
    static long tpcap;
    long n, m, e;
    Str w;
    memset(&w, 0, sizeof(w));
    pc++;
    n = int_expr();
    if (err_flag == 1) return;
    if (is_kw("GOTO") || is_kw("GOSUB")) {
        s_set(&w, tk[pc].s, tk[pc].sl);
        pc++;
    } else {
        syn();
        return;
    }
    m = 0;
    for (;;) {
        m++;
        NEED(tp, tpcap, m + 2);
        tp[m] = pc;
        pc++;
        if (is_op(9)) pc++;
        else break;
    }
    if (n < 1 || n > m) {
        s_free(&w);
        return;
    }
    e = pc;
    if (s_eq(&w, "GOSUB")) {
        gsp++;
        NEED(g_ret, g_ret_cap, gsp + 2);
        g_ret[gsp] = e;
    }
    goto_tok(tp[n]);
    if (err_flag == 1 && s_eq(&w, "GOSUB")) gsp--;
    s_free(&w);
}

static void do_onerror(void)
{
    long t;
    pc++;
    if (is_kw("GOTO")) {
        pc++;
        if (tk[pc].t == 1 && tk[pc].num == 0.0) {
            on_err = 0;
            pc++;
        } else {
            t = resolve_label(pc);
            if (t == 0) rt_error(8, "Undefined line number");
            else on_err = t;
            pc++;
        }
    } else if (is_kw("RESUME")) {
        pc++;
        if (tk[pc].t == 3 || tk[pc].t == 4) pc++;
        on_err = -1;
    } else syn();
}

static void do_resume(void)
{
    pc++;
    if (redo_flag == 0) {
        rt_error(20, "RESUME without error");
        return;
    }
    redo_flag = 0;
    if (at_end() == 1) pc = res_pc;
    else if (tk[pc].t == 4 && tks(pc, "NEXT")) pc = stmt_end(res_pc);
    else goto_tok(pc);
}

static void do_dim(void)
{
    long slot, hasp, ob, ocnt, ncnt, i, lo, hi, e, l1, h1, l2, h2, l3,
        h3;
    int nd0, preserve, skip, isre;
    Var *v;
    isre = 0;
    if (tks(pc, "REDIM")) isre = 1;
    (void)isre;
    pc++;
    preserve = 0;
    if (is_kw("PRESERVE")) {
        preserve = 1;
        pc++;
    }
    if (is_kw("SHARED")) pc++;
    if (is_kw("AS")) {
        pc++;
        if (tk[pc].t == 8) pc++;
    }
    for (;;) {
        if (tk[pc].t != 3) {
            syn();
            return;
        }
        slot = tk[pc].k;
        hasp = tk[pc].x;
        pc++;
        l1 = optbase;
        h1 = 0;
        l2 = optbase;
        h2 = 0;
        l3 = optbase;
        h3 = 0;
        skip = 0;
        if (hasp == 1) {
            pc++;
            nd0 = 0;
            for (;;) {
                e = int_expr();
                if (err_flag == 1) return;
                if (is_kw("TO")) {
                    pc++;
                    lo = e;
                    hi = int_expr();
                } else {
                    lo = optbase;
                    hi = e;
                }
                nd0++;
                if (nd0 == 1) {
                    l1 = lo;
                    h1 = hi;
                } else if (nd0 == 2) {
                    l2 = lo;
                    h2 = hi;
                } else if (nd0 == 3) {
                    l3 = lo;
                    h3 = hi;
                } else {
                    syn();
                    return;
                }
                if (is_op(9)) pc++;
                else break;
            }
            need_rparen();
            if (err_flag == 1) return;
            if (vars[slot].stat == 1 && vars[slot].isarr == 1)
                skip = 1;
            if (skip == 0) {
                v = &vars[slot];
                ob = v->base;
                ocnt = 0;
                if (v->isarr == 1 && v->nd == 1)
                    ocnt = v->hi[0] - v->lo[0] + 1;
                dim_array(slot, nd0, l1, h1, l2, h2, l3, h3);
                if (err_flag == 1) return;
                if (preserve == 1 && nd0 == 1 && ocnt > 0) {
                    ncnt = h1 - l1 + 1;
                    if (ocnt < ncnt) ncnt = ocnt;
                    for (i = 0; i < ncnt; i++) {
                        if (vars[slot].kind == 2)
                            s_cpy(&pool_s[vars[slot].base + i],
                            &pool_s[ob + i]);
                        else pool_n[vars[slot].base + i]
                            = pool_n[ob + i];
                    }
                }
            }
        } else if (vars[slot].stat == 0) {
            vars[slot].n = 0.0;
            s_clr(&vars[slot].s);
        }
        if (is_kw("AS")) {
            pc++;
            if (tk[pc].t == 8) pc++;
        }
        if (is_op(12) && hasp == 0) {
            pc++;
            ex_prec(1);
            if (err_flag == 1) return;
            store_val(slot, 0);
        }
        if (is_op(9)) pc++;
        else break;
    }
}

static void do_const(void)
{
    long slot;
    pc++;
    for (;;) {
        if (tk[pc].t != 3) {
            syn();
            return;
        }
        slot = tk[pc].k;
        pc++;
        if (is_kw("AS")) {
            pc++;
            if (tk[pc].t == 8) pc++;
        }
        need_op(12);
        ex_prec(1);
        if (err_flag == 1) return;
        store_val(slot, 0);
        vars[slot].cnst = 1;
        if (is_op(9)) pc++;
        else break;
    }
}

static void do_erase(void)
{
    pc++;
    while (tk[pc].t == 3) {
        vars[tk[pc].k].isarr = 0;
        pc++;
        if (is_op(7)) {
            pc++;
            need_rparen();
        }
        if (is_op(9)) pc++;
    }
}

static void do_clear(void)
{
    long i;
    for (i = 1; i <= nvars; i++) {
        if (vars[i].cnst == 0) {
            vars[i].n = 0.0;
            s_clr(&vars[i].s);
            vars[i].isarr = 0;
        }
    }
    dptr = 1;
    pc = stmt_end(pc);
}

static void do_option(void)
{
    pc++;
    if (tk[pc].t == 3 && tks(pc, "BASE")) {
        pc++;
        optbase = int_expr();
    } else pc = stmt_end(pc);
}

static void do_randomize(void)
{
    double x;
    long i;
    pc++;
    if (at_end() == 1) x = floor(clock_seconds() * 1000000.0);
    else x = num_expr();
    if (err_flag == 1) return;
    rnd_state = fmod(rint_d(fmod(fabs(x), 2147483646.0)), 2147483646.0)
        + 1.0;
    for (i = 1; i <= 4; i++) rnd_next();
}

static void do_cls(void)
{
    pc++;
    if (ansi == 1) outz("\033[2J\033[H");
    out_col = 0;
}

static void do_locate(void)
{
    long r, c;
    char b[64];
    pc++;
    r = -1;
    c = -1;
    if (at_end() == 0 && is_op(9) == 0) r = int_expr();
    if (is_op(9)) {
        pc++;
        if (at_end() == 0 && is_op(9) == 0) c = int_expr();
    }
    pc = stmt_end(pc);
    if (err_flag == 1) return;
    if (ansi == 1) {
        if (r > 0 && c > 0) {
            sprintf(b, "\033[%ld;%ldH", r, c);
            outz(b);
        } else if (r > 0) {
            sprintf(b, "\033[%ld;1H", r);
            outz(b);
        } else if (c > 0) {
            sprintf(b, "\033[%ldG", c);
            outz(b);
        }
    }
    if (c > 0) out_col = c - 1;
}

static long ansi_color(long n, int bg)
{
    long base, m;
    m = n % 8;
    /* BASIC colour order is black blue green cyan red magenta yellow
       white */
    if (m == 1) base = 4;
    else if (m == 3) base = 6;
    else if (m == 4) base = 1;
    else if (m == 6) base = 3;
    else if (m == 2) base = 2;
    else if (m == 5) base = 5;
    else if (m == 0) base = 0;
    else base = 7;
    if (bg == 1) {
        if (n >= 8) return 100 + base;
        return 40 + base;
    }
    if (n >= 8) return 90 + base;
    return 30 + base;
}

static void do_color(void)
{
    long f, b;
    char nb[64];
    pc++;
    f = -1;
    b = -1;
    if (at_end() == 0 && is_op(9) == 0) f = int_expr();
    if (is_op(9)) {
        pc++;
        if (at_end() == 0 && is_op(9) == 0) b = int_expr();
    }
    pc = stmt_end(pc);
    if (err_flag == 1) return;
    if (ansi == 1) {
        if (f >= 0) {
            sprintf(nb, "\033[%ldm", ansi_color(f, 0));
            outz(nb);
        }
        if (b >= 0) {
            sprintf(nb, "\033[%ldm", ansi_color(b, 1));
            outz(nb);
        }
    }
}

static void do_sleep(void)
{
    double x, t0, t1;
    pc++;
    flush_out();
    if (at_end() == 1) {
        (void)getc(stdin);
        return;
    }
    x = num_expr();
    if (err_flag == 1) return;
    t0 = clock_seconds();
    for (;;) {
        t1 = clock_seconds();
        if (t1 < t0 || t1 - t0 >= x) break;
    }
}
