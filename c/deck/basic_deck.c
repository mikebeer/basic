/* ---------- input ---------- */
/* reads a line into out; on an error err_flag is set */
static void read_text_line(long n, Str *out)
{
    FILE *fh;
    int e;
    s_clr(out);
    if (n == 0) {
        flush_out();
        fh = stdin;
    } else {
        if (n < 1 || n > NFILES) {
            rt_error(52, "Bad file name or number");
            return;
        }
        if (fl_mode[n] != 1) {
            rt_error(54, "Bad file mode");
            return;
        }
        if (fl_has[n] == 1) {
            fl_has[n] = 0;
            s_cpy(out, &fl_pend[n]);
            return;
        }
        if (fl_eof[n] == 1) {
            rt_error(62, "Input past end of file");
            return;
        }
        fh = fl_fp[n];
    }
    e = read_line(fh, out);
    if (e > 0 && out->n == 0) {
        if (n > 0) fl_eof[n] = 1;
        rt_error(62, "Input past end of file");
        return;
    }
    if (out->n > 0 && out->p[out->n - 1] == '\r') {
        out->n--;
        out->p[out->n] = '\0';
    }
}

static void split_fields(const Str *line)
{
    long n, i;
    int c, q, inq;
    Str w;
    memset(&w, 0, sizeof(w));
    n = line->n;
    inp_n = 0;
    q = 0;
    inq = 0;
    for (i = 0; i < n; i++) {
        c = (unsigned char)line->p[i];
        if (inq == 1) {
            if (c == '"') inq = 0;
            else s_catc(&w, c);
        } else if (c == '"') {
            /* a quote starts a quoted field only when nothing but
               blanks precedes it */
            long a;
            a = 0;
            while (a < w.n && w.p[a] == ' ') a++;
            if (a == w.n) {
                inq = 1;
                q = 1;
                s_clr(&w);
            } else s_catc(&w, c);
        } else if (c == ',') {
            inp_n++;
            NEED(inp_f, inp_cap, inp_n + 2);
            if (q == 1) s_cpy(&inp_f[inp_n], &w);
            else strip_into(&inp_f[inp_n], SP(w), w.n, 'B', ' ');
            s_clr(&w);
            q = 0;
        } else s_catc(&w, c);
    }
    inp_n++;
    NEED(inp_f, inp_cap, inp_n + 2);
    if (q == 1) s_cpy(&inp_f[inp_n], &w);
    else strip_into(&inp_f[inp_n], SP(w), w.n, 'B', ' ');
    s_free(&w);
}

/* assign a text field to a variable; returns 0 when a number is
   malformed */
static int assign_text(long slot, long idx, const Str *txt)
{
    Str t;
    int r;
    if (vars[slot].kind == 2) {
        s_cpy(&rs, txt);
        rt = 1;
        store_val(slot, idx);
        return 1;
    }
    rn = valparse(txt);
    rt = 0;
    r = 1;
    if (val_ok == 0) {
        memset(&t, 0, sizeof(t));
        strip_into(&t, SP(*txt), txt->n, 'B', ' ');
        if (t.n != 0) r = 0;
        s_free(&t);
    }
    if (r == 0) return 0;
    store_val(slot, idx);
    return 1;
}

static void do_input(void)
{
    static long *sl, *ix;
    static long vcap, vcap2;
    long n, nv, i, j;
    Str prompt, line;
    int isl, qm, ok;
    memset(&prompt, 0, sizeof(prompt));
    memset(&line, 0, sizeof(line));
    isl = 0;
    pc++;
    if (tks(stmt_pc, "LINEINPUT")) isl = 1;
    if (is_op(10)) pc++;
    n = file_arg();
    qm = 1;
    if (n == 0 && tk[pc].t == 2) {
        s_set(&prompt, tk[pc].s, tk[pc].sl);
        pc++;
        if (is_op(10)) pc++;
        else if (is_op(9)) {
            pc++;
            qm = 0;
        } else syn();
    }
    nv = 0;
    for (;;) {
        if (err_flag == 1) goto done;
        lval();
        if (err_flag == 1) goto done;
        nv++;
        NEED(sl, vcap, nv + 2);
        NEED(ix, vcap2, nv + 2);
        sl[nv] = lv_slot;
        ix[nv] = lv_idx;
        if (is_op(9)) pc++;
        else break;
    }
    if (isl == 1) {
        if (n == 0) outs(SP(prompt), prompt.n);
        read_text_line(n, &line);
        if (err_flag == 1) goto done;
        s_cpy(&rs, &line);
        rt = 1;
        store_val(sl[1], ix[1]);
        goto done;
    }
    for (;;) {
        if (n == 0) {
            outs(SP(prompt), prompt.n);
            if (qm == 1) outs("? ", 2);
        }
        ok = 1;
        i = 1;
        while (i <= nv && ok == 1) {
            read_text_line(n, &line);
            if (err_flag == 1) goto done;
            split_fields(&line);
            j = 1;
            while (j <= inp_n && i <= nv) {
                if (assign_text(sl[i], ix[i], &inp_f[j]) == 0) {
                    ok = 0;
                    break;
                }
                i++;
                j++;
            }
            if (ok == 1 && i <= nv && n == 0) outs("?" "? ", 3);
        }
        if (ok == 1) break;
        if (n != 0) {
            rt_error(13, "Type mismatch");
            goto done;
        }
        outs("?Redo from start\n", 17);
    }
done:
    s_free(&prompt);
    s_free(&line);
}

/* ---------- DATA / READ / RESTORE ---------- */
static void do_read(void)
{
    Str t;
    memset(&t, 0, sizeof(t));
    pc++;
    for (;;) {
        lval();
        if (err_flag == 1) return;
        if (dptr > nd) {
            rt_error(4, "Out of DATA");
            return;
        }
        s_set(&t, dat[dptr].s, dat[dptr].sl);
        if (assign_text(lv_slot, lv_idx, &t) == 0) {
            rt_error(13, "Type mismatch");
            s_free(&t);
            return;
        }
        dptr++;
        if (is_op(9)) pc++;
        else break;
    }
    s_free(&t);
}

static void do_restore(void)
{
    long t, li, v;
    char kb[64];
    pc++;
    dptr = 1;
    if (at_end() == 0) {
        if (tk[pc].t == 1) {
            sprintf(kb, "%.0f", rint_d(tk[pc].num));
            v = hm_get(&lmap, kb);
        } else v = hm_get(&lmap, tk[pc].s);
        pc++;
        if (v == 0) {
            rt_error(8, "Undefined line number");
            return;
        }
        li = v;
        dptr = nd + 1;
        for (t = 1; t <= nd; t++) {
            if (dat[t].line >= li) {
                dptr = t;
                break;
            }
        }
    }
}

/* ---------- files ---------- */
static void do_open(void)
{
    Str fnm, mode, w;
    int md;
    long n;
    const char *rmode;
    FILE *f;
    memset(&fnm, 0, sizeof(fnm));
    memset(&mode, 0, sizeof(mode));
    memset(&w, 0, sizeof(w));
    n = 0;
    pc++;
    if (!str_expr(&fnm)) goto done;
    md = 0;
    if (is_op(9)) {
        /* OPEN "I", #1, "file" */
        pc++;
        s_set(&mode, SP(fnm), fnm.n > 0 ? 1 : 0);
        up_str(&mode);
        if (is_op(18)) pc++;
        n = int_expr();
        if (is_op(9)) pc++;
        str_expr(&fnm);
        if (s_eq(&mode, "I")) md = 1;
        else if (s_eq(&mode, "O")) md = 2;
        else if (s_eq(&mode, "A")) md = 3;
    } else {
        md = 3;
        if (is_kw("FOR")) {
            pc++;
            s_set(&w, tk[pc].s, tk[pc].sl);
            up_str(&w);
            pc++;
            if (s_eq(&w, "INPUT")) md = 1;
            else if (s_eq(&w, "OUTPUT")) md = 2;
            else if (s_eq(&w, "APPEND")) md = 3;
            else md = -1;
        } else md = 3;
        while (is_kw("AS") == 0 && at_end() == 0) pc++;
        if (is_kw("AS")) pc++;
        if (is_op(18)) pc++;
        n = int_expr();
        while (at_end() == 0) pc++;
    }
    if (err_flag == 1) goto done;
    if (md <= 0) {
        rt_error(54, "Bad file mode");
        goto done;
    }
    if (n < 1 || n > NFILES) {
        rt_error(52, "Bad file name or number");
        goto done;
    }
    if (fl_mode[n] != 0) {
        rt_error(55, "File already open");
        goto done;
    }
    if (md == 1) rmode = "r";
    else if (md == 2) rmode = "w";
    else rmode = "a";
    f = fopen(SP(fnm), rmode);
    if (f == NULL) {
        if (md == 1) rt_error(53, "File not found");
        else rt_error(70, "Permission denied");
        goto done;
    }
    fl_fp[n] = f;
    fl_mode[n] = md;
    fl_eof[n] = 0;
    fl_has[n] = 0;
done:
    s_free(&fnm);
    s_free(&mode);
    s_free(&w);
}

static void close_file(long n)
{
    if (n < 1 || n > NFILES) return;
    if (fl_mode[n] == 0) return;
    if (fl_fp[n] != NULL) fclose(fl_fp[n]);
    fl_fp[n] = NULL;
    fl_mode[n] = 0;
    fl_has[n] = 0;
    fl_eof[n] = 0;
}

static void close_all(void)
{
    long i;
    for (i = 1; i <= NFILES; i++)
        if (fl_mode[i] != 0) close_file(i);
}

static void do_close(void)
{
    long n;
    pc++;
    if (at_end() == 1) {
        close_all();
        return;
    }
    for (;;) {
        if (is_op(18)) pc++;
        n = int_expr();
        if (err_flag == 1) return;
        close_file(n);
        if (is_op(9)) pc++;
        else break;
    }
}

