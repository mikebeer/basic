/* sm: 0 normal, 1 shared, 2 static;  ak: forced kind or -1 */
static long getslot(const char *key, int sm, int ak)
{
    Str lk;
    long v, s0, g0;
    memset(&lk, 0, sizeof(lk));
    if (cur_proc > 0) {
        s_cats(&lk, procs[cur_proc].name);
        s_catc(&lk, ':');
        s_cats(&lk, key);
        v = hm_get(&nm, SP(lk));
        if (v != 0) {
            s0 = v;
            if (ak >= 0) vars[s0].kind = ak;
            s_free(&lk);
            return s0;
        }
        v = hm_get(&nm, key);
        if (v != 0) {
            g0 = v;
            if (vars[g0].shared == 1) {
                s_free(&lk);
                return g0;
            }
        }
        if (sm == 1) {
            if (v == 0) g0 = newslot(key, key, 0);
            else g0 = v;
            vars[g0].shared = 1;
            s_free(&lk);
            return g0;
        }
        s0 = newslot(SP(lk), key, cur_proc);
        if (sm == 2) vars[s0].stat = 1;
        if (ak >= 0) vars[s0].kind = ak;
        s_free(&lk);
        return s0;
    }
    v = hm_get(&nm, key);
    if (v != 0) s0 = v;
    else s0 = newslot(key, key, 0);
    if (sm == 1) vars[s0].shared = 1;
    if (ak >= 0) vars[s0].kind = ak;
    return s0;
}

static void emit(int ty, double nv, const char *sv, long sl, long kv,
    long fv, long li)
{
    Tok *t;
    ntk++;
    NEED(tk, tk_cap, ntk + 12);
    t = &tk[ntk];
    t->t = ty;
    t->num = nv;
    if (t->s != NULL) free(t->s);
    t->s = xstrdup(sv, sl);
    t->sl = sl;
    t->k = kv;
    t->f = fv;
    t->x = 0;
    t->y = 0;
    t->l = li;
}

static void emitz(int ty, double nv, const char *sv, long kv, long fv,
    long li)
{
    emit(ty, nv, sv, (long)strlen(sv), kv, fv, li);
}

/* ---------- the tokenizer: one source line -> tokens ---------- */
static void tokenize_line(const char *txt, long n, long li)
{
    long i, j, k, slot, ls, depth, lastkwpos, kd;
    int c, c2, e, sx, atstart, smode, asknd, want_proc, inhdr, isarr;
    Str w, u, bu, lastkw, nx;
    char cb[3];
    double nv;
    long p;
    const char *cw;

    memset(&w, 0, sizeof(w));
    memset(&u, 0, sizeof(u));
    memset(&bu, 0, sizeof(bu));
    memset(&lastkw, 0, sizeof(lastkw));
    memset(&nx, 0, sizeof(nx));
    i = 1;
    ln_start[li] = ntk + 1;
    ln_num[li] = -1;
    ls = 0;
    depth = 0;
    atstart = 1;
    smode = 0;
    asknd = -1;
    want_proc = 0;
    lastkwpos = 0;
    inhdr = 0;
    while (i <= n
        && (ch_at(txt, n, i) == ' ' || ch_at(txt, n, i) == '\t')) i++;
    j = i;
    while (j <= n && is_digit(ch_at(txt, n, j))) j++;
    if (j > i) {
        double dv;
        char nb[64];
        long nl;
        nl = j - i;
        if (nl > 40) nl = 40;
        memcpy(nb, txt + i - 1, (size_t)nl);
        nb[nl] = '\0';
        dv = strtod(nb, NULL);
        k = dv > 2000000000.0 ? 2000000000L : (long)dv;
        ln_num[li] = k;
        sprintf(nb, "%ld", k);
        hm_set(&lmap, nb, li);
        i = j;
        atstart = 1;
    } else if (ch_at(txt, n, i) == '#') {
        i = n + 1;
    }
    while (i <= n) {
        c = ch_at(txt, n, i);
        if (c == ' ' || c == '\t') {
            i++;
            continue;
        }
        if (c == '\'') break;
        c2 = ch_at(txt, n, i + 1);
        /* ---------- numbers ---------- */
        if (is_digit(c) || (c == '.' && is_digit(c2))) {
            j = i;
            while (j <= n && is_digit(ch_at(txt, n, j))) j++;
            if (j <= n && ch_at(txt, n, j) == '.') {
                j++;
                while (j <= n && is_digit(ch_at(txt, n, j))) j++;
            }
            if (j <= n) {
                e = to_up(ch_at(txt, n, j));
                if (e == 'E' || e == 'D') {
                    k = j + 1;
                    if (k <= n
                        && (ch_at(txt, n, k) == '+'
                        || ch_at(txt, n, k) == '-')) k++;
                    if (k <= n && is_digit(ch_at(txt, n, k))) {
                        j = k;
                        while (j <= n && is_digit(ch_at(txt, n, j)))
                            j++;
                    }
                }
            }
            s_set(&w, txt + i - 1, j - i);
            up_str(&w);
            for (k = 0; k < w.n; k++)
                if (w.p[k] == 'D') w.p[k] = 'E';
            nv = numtofloat(SP(w));
            i = j;
            sx = ch_at(txt, n, i);
            if (sx == '%' || sx == '!' || sx == '#') i++;
            else if (sx == '&' && !is_alnum(ch_at(txt, n, i + 1))) i++;
            emit(1, nv, "", 0, 0, 0, li);
            atstart = 0;
            continue;
        }
        /* ---------- &H &O &B literals ---------- */
        if (c == '&') {
            sx = to_up(c2);
            if (sx == 'H' || sx == 'O' || sx == 'B') {
                int base;
                j = i + 2;
                while (j <= n && is_alnum(ch_at(txt, n, j))) j++;
                s_set(&w, txt + i + 1, j - i - 2);
                up_str(&w);
                if (w.n > 0 && w.p[w.n - 1] == '&') w.n--,
                    w.p[w.n] = '\0';
                if (w.n == 0) s_set(&w, "0", 1);
                base = sx == 'H' ? 16 : (sx == 'B' ? 2 : 8);
                nv = 0.0;
                for (k = 0; k < w.n; k++) {
                    p
                        = (long)(strchr("0123456789ABCDEF", w.p[k])
                        ? strchr("0123456789ABCDEF", w.p[k])
                        - "0123456789ABCDEF" : 99);
                    if (p >= base) break;
                    nv = nv * base + (double)p;
                }
                i = j;
                if (ch_at(txt, n, i) == '&') i++;
                emit(1, nv, "", 0, 0, 0, li);
                atstart = 0;
                continue;
            }
        }
        /* ---------- strings ---------- */
        if (c == '"') {
            s_clr(&w);
            j = i + 1;
            for (;;) {
                if (j > n) break;
                e = ch_at(txt, n, j);
                if (e == '"') {
                    if (ch_at(txt, n, j + 1) == '"') {
                        s_catc(&w, '"');
                        j += 2;
                        continue;
                    }
                    break;
                }
                s_catc(&w, e);
                j++;
            }
            i = j + 1;
            emit(2, 0.0, SP(w), w.n, 0, 0, li);
            atstart = 0;
            continue;
        }
        /* ---------- identifiers and keywords ---------- */
        if (is_letter(c)) {
            j = i;
            while (j <= n && is_alnum(ch_at(txt, n, j))) j++;
            s_set(&w, txt + i - 1, j - i);
            sx = ch_at(txt, n, j);
            if (sx == '$' || sx == '%' || sx == '!' || sx == '#') {
                s_catc(&w, sx);
                j++;
            } else if (sx == '&' && ch_at(txt, n, j + 1) != '&') {
                if (!is_alnum(peekchar(txt, n, j + 1))
                    && peekchar(txt, n, j + 1) != '"' &&
                    peekchar(txt, n, j + 1) != '(') {
                    s_catc(&w, sx);
                    j++;
                }
            }
            i = j;
            s_cpy(&u, &w);
            up_str(&u);
            if (s_eq(&u, "REM")) break;
            /* label? */
            if (atstart == 1 && ch_at(txt, n, i) == ':'
                && wordpos(SP(u), kws) == 0) {
                hm_set(&lmap, SP(u), li);
                i++;
                continue;
            }
            atstart = 0;
            /* compound keywords */
            if (s_eq(&u, "END") || s_eq(&u, "EXIT")
                || s_eq(&u, "CONTINUE") || s_eq(&u, "SELECT") ||
                s_eq(&u, "CASE") || s_eq(&u, "LINE") || s_eq(&u, "GO")
                    || s_eq(&u, "ON")) {
                cw = compound(SP(u), txt, n, i);
                if (cw[0] != '\0') {
                    s_set(&u, cw, (long)strlen(cw));
                    i = pw_end;
                }
            }
            /* operator words */
            kd = opcode(SP(u));
            if (kd >= 31) {
                emit(5, 0.0, SP(u), u.n, kd, 0, li);
                continue;
            }
            /* statement keywords */
            if (wordpos(SP(u), kws) > 0) {
                if (s_eq(&u, "DECLARE")) {
                    i = n + 1;
                    continue;
                }
                if (s_eq(&u, "DEFINT") || s_eq(&u, "DEFSNG")
                    || s_eq(&u, "DEFDBL") || s_eq(&u, "DEFSTR") ||
                    s_eq(&u, "DEFLNG")) {
                    do_defxxx(SP(u), txt + i - 1, n - i + 1);
                    i = n + 1;
                    continue;
                }
                if (s_eq(&u, "AS") && !s_eq(&lastkw, "OPEN")) {
                    peekword(txt, n, i, &nx);
                    if (s_eq(&nx, "UNSIGNED")) {
                        i = pw_end;
                        peekword(txt, n, i, &nx);
                    }
                    if (nx.n > 0) {
                        i = pw_end;
                        kd = typekind(&nx);
                        if (s_eq(&nx, "LONG")
                            && peekword_is(txt, n, i, "LONG"))
                            i = pw_end;
                        if ((s_eq(&nx, "STRING")
                            || s_eq(&nx, "ZSTRING"))
                            && peekchar(txt, n, i) == '*') {
                            j = i;
                            while (j <= n && ch_at(txt, n, j) != '*')
                                j++;
                            j++;
                            while (j <= n
                                && (ch_at(txt, n, j) == ' '
                                || is_digit(ch_at(txt, n, j)))) j++;
                            i = j;
                        }
                        if (peekword_is(txt, n, i, "PTR")) i = pw_end;
                        emitz(4, 0.0, "AS", wordpos("AS", kws), 0, li);
                        emit(8, 0.0, SP(nx), nx.n, kd, 0, li);
                        if (lastkwpos == ntk - 2 &&
                            (s_eq(&lastkw, "DIM")
                                || s_eq(&lastkw, "REDIM")
                                || s_eq(&lastkw, "SHARED") ||
                             s_eq(&lastkw, "STATIC")
                                 || s_eq(&lastkw, "COMMON")
                                 || s_eq(&lastkw, "LOCAL") ||
                             s_eq(&lastkw, "CONST")))
                            asknd = (int)kd;
                        else if (ls > 0) vars[ls].kind = (int)kd;
                        continue;
                    }
                }
                if (s_eq(&u, "SHARED")) smode = 1;
                if (s_eq(&u, "STATIC") && cur_proc > 0) smode = 2;
                if (s_eq(&u, "SUB") && cur_proc == 0) want_proc = 1;
                if (s_eq(&u, "CONST") && cur_proc == 0) smode = 1;
                if (s_eq(&u, "FUNCTION") && cur_proc == 0)
                    want_proc = 2;
                if (s_eq(&u, "ENDSUB") || s_eq(&u, "ENDFUNCTION")) {
                    emit(4, 0.0, SP(u), u.n, wordpos(SP(u), kws), 0,
                        li);
                    cur_proc = 0;
                    continue;
                }
                emit(4, 0.0, SP(u), u.n, wordpos(SP(u), kws), 0, li);
                s_cpy(&lastkw, &u);
                lastkwpos = ntk;
                if (s_eq(&u, "DATA")) {
                    i = capture_data(txt, n, i, li);
                    continue;
                }
                continue;
            }
            /* builtin functions */
            s_cpy(&bu, &u);
            if (bu.n > 0 && bu.p[bu.n - 1] == '$') {
                bu.n--;
                bu.p[bu.n] = '\0';
            }
            if (want_proc == 0) {
                long fi;
                fi = wordpos(SP(bu), fnl);
                if (fi > 0 && peekchar(txt, n, i) != '('
                    && wordpos(SP(bu), nopar) == 0) fi = 0;
                if (fi > 0) {
                    emit(3, 0.0, SP(bu), bu.n, 0, fi, li);
                    continue;
                }
            }
            /* identifier */
            isarr = peekchar(txt, n, i) == '(';
            if (want_proc > 0) {
                np++;
                NEED(procs, np_cap, np + 1);
                procs[np].name = xstrdup(SP(u), u.n);
                procs[np].isfn = want_proc - 1;
                procs[np].pc = ntk;
                procs[np].body = 0;
                procs[np].end = 0;
                procs[np].ret = 0;
                procs[np].pfirst = 0;
                procs[np].pcnt = 0;
                cur_proc = np;
                if (want_proc == 2) {
                    slot = getslot(SP(u), 0, -1);
                    procs[np].ret = slot;
                    ls = slot;
                } else slot = 0;
                want_proc = 0;
                inhdr = 1;
                emit(3, 0.0, SP(u), u.n, slot, 0, li);
                continue;
            }
            if (isarr) {
                Str kk;
                memset(&kk, 0, sizeof(kk));
                s_cpy(&kk, &u);
                s_catc(&kk, '(');
                slot = getslot(SP(kk), smode, asknd);
                s_free(&kk);
            } else slot = getslot(SP(u), smode, asknd);
            if (depth == 0 || (inhdr == 1 && depth == 1)) ls = slot;
            emit(3, 0.0, SP(u), u.n, slot, 0, li);
            tk[ntk].x = isarr;
            continue;
        }
        /* ---------- operators and punctuation ---------- */
        if ((c == '<' && c2 == '=') || (c == '=' && c2 == '<')) {
            emitz(5, 0.0, "<=", 15, 0, li);
            i += 2;
        } else if ((c == '>' && c2 == '=') || (c == '=' && c2 == '>'))
            {
            emitz(5, 0.0, ">=", 16, 0, li);
            i += 2;
        } else if ((c == '<' && c2 == '>') || (c == '>' && c2 == '<'))
            {
            emitz(5, 0.0, "<>", 17, 0, li);
            i += 2;
        } else if (c == '?') {
            emitz(4, 0.0, "PRINT", wordpos("PRINT", kws), 0, li);
            s_set(&lastkw, "PRINT", 5);
            i++;
        } else {
            cb[0] = (char)c;
            cb[1] = '\0';
            kd = opcode(cb);
            if (kd == 7) depth++;
            if (kd == 8) {
                depth--;
                if (depth == 0 && inhdr == 1) {
                    if (procs[cur_proc].isfn == 1)
                        ls = procs[cur_proc].ret;
                    else ls = 0;
                }
            }
            if (kd == 11) {
                smode = 0;
                asknd = -1;
                s_clr(&lastkw);
            }
            emit(5, 0.0, cb, 1, kd, 0, li);
            i++;
        }
    }
    emitz(6, 0.0, "", 0, 0, li);
    s_free(&w);
    s_free(&u);
    s_free(&bu);
    s_free(&lastkw);
    s_free(&nx);
}

static void do_defxxx(const char *kw, const char *rest, long m)
{
    long i, a, b;
    int kd, c, li;
    if (strcmp(kw, "DEFSTR") == 0) kd = 2;
    else if (strcmp(kw, "DEFINT") == 0 || strcmp(kw, "DEFLNG") == 0)
        kd = 1;
    else kd = 0;
    i = 1;
    while (i <= m) {
        c = ch_at(rest, m, i);
        li = letter_index(c);
        if (li > 0 && !is_digit(c) && c != '_') {
            a = li;
            b = a;
            i++;
            if (ch_at(rest, m, i) == '-') {
                c = ch_at(rest, m, i + 1);
                if (letter_index(c) > 0) b = letter_index(c);
                i += 2;
            }
            while (a <= b) {
                defkind[a] = kd;
                a++;
            }
        } else i++;
    }
}

static void add_data(const char *w, long wl, long q, long li)
{
    nd++;
    NEED(dat, nd_cap, nd + 1);
    if (dat[nd].s != NULL) free(dat[nd].s);
    dat[nd].s = xstrdup(w, wl);
    dat[nd].sl = wl;
    dat[nd].q = q;
    dat[nd].line = li;
}

/* DATA items: captured at tokenize time; returns the position after
   the DATA text */
static long capture_data(const char *txt, long n, long p0, long li)
{
    long i, q;
    int c, inq;
    Str w, t;
    memset(&w, 0, sizeof(w));
    memset(&t, 0, sizeof(t));
    i = p0;
    while (i <= n
        && (ch_at(txt, n, i) == ' ' || ch_at(txt, n, i) == '\t')) i++;
    q = 0;
    inq = 0;
    while (i <= n) {
        c = ch_at(txt, n, i);
        if (inq == 1) {
            if (c == '"') inq = 0;
            else s_catc(&w, c);
            i++;
            continue;
        }
        if (c == '"') {
            inq = 1;
            q = 1;
            i++;
            continue;
        }
        if (c == ',') {
            if (q == 0) {
                strip_into(&t, SP(w), w.n, 'B', ' ');
                add_data(SP(t), t.n, q, li);
            } else add_data(SP(w), w.n, q, li);
            s_clr(&w);
            q = 0;
            i++;
            while (i <= n
                && (ch_at(txt, n, i) == ' '
                || ch_at(txt, n, i) == '\t')) i++;
            continue;
        }
        if (c == ':') break;
        if (c == '\'' && q == 0) {
            i = n + 1;
            break;
        }
        s_catc(&w, c);
        i++;
    }
    if (q == 0) {
        strip_into(&t, SP(w), w.n, 'B', ' ');
        add_data(SP(t), t.n, q, li);
    } else add_data(SP(w), w.n, q, li);
    s_free(&w);
    s_free(&t);
    return i;
}
