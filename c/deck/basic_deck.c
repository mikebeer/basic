static void report_error(void)
{
    long li;
    char s[400];
    li = tk[stmt_pc].l;
    flush_out();
    if (li >= 1 && ln_num[li] >= 0)
        sprintf(s, "%s in %ld\n", last_error_text, ln_num[li]);
    else sprintf(s, "%s in line %ld\n", last_error_text, li);
    errs(s);
}

static int handle_error(void)
{
    if (cfp > 0) return 0;
    if (on_err != 0 && redo_flag == 0) {
        res_pc = mstmt;
        err_flag = 0;
        if (on_err < 0) {
            pc = stmt_end(mstmt);
            return 1;
        }
        redo_flag = 1;
        pc = on_err;
        return 1;
    }
    report_error();
    halted = 1;
    rc_exit = 1;
    return 0;
}

static void run_loop(void)
{
    long fsp0, ssp0;
    int t;
    fsp0 = fsp;
    ssp0 = ssp;
    for (;;) {
        if (halted == 1 || retflag == 1) break;
        t = tk[pc].t;
        if (t == 6) {
            pc++;
            continue;
        }
        if (t == 5 && tk[pc].k == 11) {
            pc++;
            continue;
        }
        if (t == 7) {
            halted = 1;
            break;
        }
        stmt_pc = pc;
        if (cfp == 0) mstmt = pc;
        if (t == 4) exec_kw();
        else if (t == 3) exec_assign();
        else syn();
        if (err_flag == 1) {
            if (handle_error() == 0) break;
        }
    }
    fsp = fsp0;
    ssp = ssp0;
}

static void call_sub(long r)
{
    long base, na;
    base = ab_cnt;
    na = 0;
    if (is_op(7)) na = eval_args(r);
    else if (at_end() == 0) {
        bare_flag = 1;
        na = eval_args(r);
        bare_flag = 0;
    }
    if (err_flag == 1) {
        ab_cnt = base;
        return;
    }
    invoke(r, base, na);
}

/* an assignment, or a SUB call written without CALL */
static void exec_assign(void)
{
    long r, k, s1, i1, at;
    double an;
    Str as0;
    if (tk[pc].f > 0) {
        r = find_proc(tk[pc].s);
        if (r > 0) {
            pc++;
            call_sub(r);
            return;
        }
        if (tks(pc, "MID")) {
            mid_assign();
            return;
        }
        syn();
        return;
    }
    r = tk[pc].y;
    if (r == 0) {
        r = find_proc(tk[pc].s);
        if (r == 0) r = BIGKIND;
        tk[pc].y = r;
    }
    if (r > 0 && r < BIGKIND
        && (tk[pc + 1].t != 5 || tk[pc + 1].k != 12)) {
        pc++;
        call_sub(r);
        return;
    }
    if (tk[pc].x == 0) {
        s1 = tk[pc].k;
        i1 = 0;
        pc++;
    } else {
        lval();
        if (err_flag == 1) return;
        s1 = lv_slot;
        i1 = lv_idx;
    }
    if (tk[pc].t == 5 && tk[pc].k == 12) {
        pc++;
        ex_prec(1);
        if (err_flag == 1) return;
        if (i1 == 0 && rt == 0 && vars[s1].kind == 0) vars[s1].n = rn;
        else store_val(s1, i1);
        return;
    }
    /* compound assignment: += -= *= /= \= ^= &= */
    if (tk[pc].t == 5 && tk[pc + 1].t == 5 && tk[pc + 1].k == 12) {
        k = tk[pc].k;
        if (k == 1 || k == 2 || k == 3 || k == 4 || k == 5 || k == 6
            || k == 19) {
            pc += 2;
            load_val(s1, i1);
            an = rn;
            at = rt;
            memset(&as0, 0, sizeof(as0));
            if (at == 1) s_cpy(&as0, &rs);
            ex_prec(1);
            if (err_flag == 1) {
                s_free(&as0);
                return;
            }
            binop(k, an, &as0, (int)at);
            s_free(&as0);
            if (err_flag == 1) return;
            store_val(s1, i1);
            return;
        }
    }
    syn();
}

static void mid_assign(void)
{
    long s1, i1, st, ln;
    Str txt, cur;
    memset(&txt, 0, sizeof(txt));
    memset(&cur, 0, sizeof(cur));
    pc++;
    need_op(7);
    lval();
    if (err_flag == 1) return;
    s1 = lv_slot;
    i1 = lv_idx;
    need_op(9);
    st = int_expr();
    ln = 1000000;
    if (is_op(9)) {
        pc++;
        ln = int_expr();
    }
    need_rparen();
    need_op(12);
    if (!str_expr(&txt)) {
        s_free(&txt);
        return;
    }
    if (err_flag == 1) {
        s_free(&txt);
        return;
    }
    load_val(s1, i1);
    s_cpy(&cur, &rs);
    if (st < 1 || st > cur.n) {
        rt_error(5, "Illegal function call");
        goto done;
    }
    if (ln > txt.n) ln = txt.n;
    if (ln > cur.n - st + 1) ln = cur.n - st + 1;
    if (ln > 0) memcpy(cur.p + st - 1, txt.p, (size_t)ln);
    s_cpy(&rs, &cur);
    rt = 1;
    store_val(s1, i1);
done:
    s_free(&txt);
    s_free(&cur);
}

