/* ---------- errors ---------- */
static void rt_error(long code, const char *msg)
{
    long li;
    if (err_flag == 1) return;
    err_flag = 1;
    err_code = code;
    strncpy(last_error_text, msg, sizeof(last_error_text) - 1);
    last_error_text[sizeof(last_error_text) - 1] = '\0';
    li = tk[stmt_pc].l;
    if (li >= 1) {
        if (ln_num[li] >= 0) err_line = ln_num[li];
        else err_line = li;
    } else err_line = 0;
}

static void syn(void)
{
    rt_error(2, "Syntax error");
}

/* ---------- output primitives ---------- */
static void outs(const char *txt, long n)
{
    long k;
    FILE *fh;
    if (n <= 0) return;
    if (out_file == 0) fh = stdout;
    else fh = fl_fp[out_file];
    if (fh != NULL) fwrite(txt, 1, (size_t)n, fh);
    k = n;
    while (k > 0 && txt[k - 1] != '\n') k--;
    if (k > 0) out_col = n - k;
    else out_col += n;
}

static void outz(const char *z)
{
    outs(z, (long)strlen(z));
}

static void flush_out(void)
{
    fflush(stdout);
}

static void errs(const char *txt)
{
    fflush(stdout);
    fputs(txt, stderr);
    fflush(stderr);
}

/* ---------- arrays ---------- */
static void dim_array(long slot, int nd0, long l1, long h1, long l2,
    long h2, long l3, long h3)
{
    double tot;
    long i, cnt;
    Var *v;
    if (h1 < l1) {
        rt_error(9, "Subscript out of range");
        return;
    }
    if (nd0 >= 2 && h2 < l2) {
        rt_error(9, "Subscript out of range");
        return;
    }
    if (nd0 >= 3 && h3 < l3) {
        rt_error(9, "Subscript out of range");
        return;
    }
    tot = (double)h1 - (double)l1 + 1.0;
    if (nd0 >= 2) tot = tot * ((double)h2 - (double)l2 + 1.0);
    if (nd0 >= 3) tot = tot * ((double)h3 - (double)l3 + 1.0);
    if (tot > 30000000.0) {
        rt_error(7, "Out of memory");
        return;
    }
    cnt = (long)tot;
    v = &vars[slot];
    v->lo[0] = l1;
    v->hi[0] = h1;
    v->lo[1] = l2;
    v->hi[1] = h2;
    v->lo[2] = l3;
    v->hi[2] = h3;
    v->nd = nd0;
    v->isarr = 1;
    if (v->kind == 2) {
        v->base = nps + 1;
        NEED(pool_s, pool_s_cap, nps + cnt + 2);
        for (i = 1; i <= cnt; i++) {
            nps++;
            s_clr(&pool_s[nps]);
        }
    } else {
        v->base = npn + 1;
        NEED(pool_n, pool_n_cap, npn + cnt + 2);
        for (i = 1; i <= cnt; i++) {
            npn++;
            pool_n[npn] = 0.0;
        }
    }
}

static void auto_dim(long slot, int nsub)
{
    if (nsub == 1) dim_array(slot, 1, optbase, 10, 0, 0, 0, 0);
    else if (nsub == 2)
        dim_array(slot, 2, optbase, 10, optbase, 10, 0, 0);
    else dim_array(slot, 3, optbase, 10, optbase, 10, optbase, 10);
}

static void need_rparen(void)
{
    if (tk[pc].t == 5 && tk[pc].k == 8) pc++;
    else rt_error(2, "Syntax error: ')' expected");
}

static void need_op(long k)
{
    if (tk[pc].t == 5 && tk[pc].k == k) pc++;
    else rt_error(2, "Syntax error");
}

/* parse (i, j, k) at pc and return the pool index of the element */
static long arr_index(long slot)
{
    int nsub;
    long i1, i2, i3, idx;
    Var *v;
    nsub = 0;
    i1 = 0;
    i2 = 0;
    i3 = 0;
    pc++;
    for (;;) {
        ex_prec(1);
        if (rt == 1) {
            rt_error(13, "Type mismatch");
            return 0;
        }
        nsub++;
        if (nsub == 1) i1 = tol(rn);
        else if (nsub == 2) i2 = tol(rn);
        else if (nsub == 3) i3 = tol(rn);
        else {
            syn();
            return 0;
        }
        if (tk[pc].t == 5 && tk[pc].k == 9) pc++;
        else break;
    }
    need_rparen();
    if (err_flag == 1) return 0;
    if (vars[slot].isarr == 0) auto_dim(slot, nsub);
    if (err_flag == 1) return 0;
    v = &vars[slot];
    if (nsub != v->nd) {
        rt_error(9, "Subscript out of range");
        return 0;
    }
    if (i1 < v->lo[0] || i1 > v->hi[0]) {
        rt_error(9, "Subscript out of range");
        return 0;
    }
    idx = i1 - v->lo[0];
    if (nsub >= 2) {
        if (i2 < v->lo[1] || i2 > v->hi[1]) {
            rt_error(9, "Subscript out of range");
            return 0;
        }
        idx = idx * (v->hi[1] - v->lo[1] + 1) + (i2 - v->lo[1]);
    }
    if (nsub >= 3) {
        if (i3 < v->lo[2] || i3 > v->hi[2]) {
            rt_error(9, "Subscript out of range");
            return 0;
        }
        idx = idx * (v->hi[2] - v->lo[2] + 1) + (i3 - v->lo[2]);
    }
    return v->base + idx;
}

/* ---------- expression evaluation (precedence climbing); result in rn
   / rs / rt ---- */
static void s_prepend(Str *d, const Str *a)
{
    if (a->n <= 0) return;
    s_reserve(d, d->n + a->n);
    memmove(d->p + a->n, SP(*d), (size_t)d->n + 1);
    memcpy(d->p, a->p, (size_t)a->n);
    d->n += a->n;
}

static void ex_prec(int minp)
{
    double ln;
    Str ls;
    int lt;
    long k, p;
    ls.p = NULL;
    ls.n = 0;
    ls.cap = 0;
    ex_unary();
    for (;;) {
        if (tk[pc].t != 5) break;
        k = tk[pc].k;
        p = prec[k];
        if (p == 0 || p < minp) break;
        pc++;
        ln = rn;
        lt = rt;
        if (lt == 1) s_cpy(&ls, &rs);
        ex_prec((int)p + 1);
        binop(k, ln, &ls, lt);
    }
    s_free(&ls);
}

static void ex_unary(void)
{
    int t;
    long k;
    I64 a;
    t = tk[pc].t;
    if (t == 1) {
        rn = tk[pc].num;
        rt = 0;
        pc++;
        return;
    }
    if (t == 2) {
        s_set(&rs, tk[pc].s, tk[pc].sl);
        rt = 1;
        pc++;
        return;
    }
    if (t == 3) {
        if (tk[pc].y == BIGKIND && tk[pc].x == 0 && tk[pc].f == 0) {
            k = tk[pc].k;
            if (vars[k].kind == 2) {
                s_cpy(&rs, &vars[k].s);
                rt = 1;
            } else {
                rn = vars[k].n;
                rt = 0;
            }
            pc++;
            return;
        }
        ex_id();
        return;
    }
    if (t == 5) {
        k = tk[pc].k;
        if (k == 7) {
            pc++;
            ex_prec(1);
            need_rparen();
            return;
        }
        if (k == 2) {
            pc++;
            ex_prec(15);
            if (rt == 1) rt_error(13, "Type mismatch");
            else rn = -rn;
            return;
        }
        if (k == 1) {
            pc++;
            ex_prec(15);
            if (rt == 1) rt_error(13, "Type mismatch");
            return;
        }
        if (k == 39) {
            pc++;
            ex_prec(7);
            if (rt == 1) rt_error(13, "Type mismatch");
            else {
                a = i64_from(rint_d(rn));
                rn = i64_to(i64_not(a));
            }
            return;
        }
    }
    syn();
    rn = 0.0;
    rt = 0;
}

static void binop(long k, double ln, const Str *ls, int lt)
{
    int tf;
    I64 a, b;
    double x, y;
    char nb[64];
    long sh;

    if (k == 1) {
        if (lt == 0 && rt == 0) rn = ln + rn;
        else if (lt == 1 && rt == 1) s_prepend(&rs, ls);
        else rt_error(13, "Type mismatch");
        return;
    }
    if (k == 19) {
        if (rt == 0) {
            fmtnum(rn, nb);
            s_set(&rs, nb, (long)strlen(nb));
        }
        if (lt == 0) {
            Str t;
            memset(&t, 0, sizeof(t));
            fmtnum(ln, nb);
            s_set(&t, nb, (long)strlen(nb));
            s_prepend(&rs, &t);
            s_free(&t);
        } else s_prepend(&rs, ls);
        rt = 1;
        return;
    }
    if (k >= 12 && k <= 17) {
        tf = 0;
        if (lt == 0 && rt == 0) {
            switch (k) {
            case 12: tf = ln == rn; break;
            case 13: tf = ln < rn; break;
            case 14: tf = ln > rn; break;
            case 15: tf = ln <= rn; break;
            case 16: tf = ln >= rn; break;
            default: tf = ln != rn; break;
            }
        } else if (lt == 1 && rt == 1) {
            int c;
            c = cmp_str(ls, &rs);
            switch (k) {
            case 12: tf = c == 0; break;
            case 13: tf = c < 0; break;
            case 14: tf = c > 0; break;
            case 15: tf = c <= 0; break;
            case 16: tf = c >= 0; break;
            default: tf = c != 0; break;
            }
        } else {
            rt_error(13, "Type mismatch");
            return;
        }
        if (tf == 1) rn = -1.0;
        else rn = 0.0;
        rt = 0;
        return;
    }
    if (lt == 1 || rt == 1) {
        rt_error(13, "Type mismatch");
        return;
    }
    switch (k) {
    case 2:
        rn = ln - rn;
        break;
    case 3:
        rn = ln * rn;
        break;
    case 4:
        if (rn == 0.0) {
            rt_error(11, "Division by zero");
            rn = 0.0;
        } else rn = ln / rn;
        break;
    case 5:
        x = fix_d(ln);
        y = fix_d(rn);
        if (y == 0.0) {
            rt_error(11, "Division by zero");
            rn = 0.0;
        } else rn = (x - fmod(x, y)) / y;
        break;
    case 36:
        x = fix_d(ln);
        y = fix_d(rn);
        if (y == 0.0) {
            rt_error(11, "Division by zero");
            rn = 0.0;
        } else rn = fmod(x, y);
        break;
    case 6:
        if (ln == 0.0 && rn < 0.0) {
            rt_error(11, "Division by zero");
            rn = 0.0;
        } else if (ln < 0.0 && floor(rn) != rn) {
            rt_error(5, "Illegal function call");
            rn = 0.0;
        } else rn = pow(ln, rn);
        break;
    case 31:
        rn
            = i64_to(i64_and(i64_from(rint_d(ln)),
            i64_from(rint_d(rn))));
        break;
    case 32:
        rn
            = i64_to(i64_or(i64_from(rint_d(ln)),
            i64_from(rint_d(rn))));
        break;
    case 33:
        rn
            = i64_to(i64_xor(i64_from(rint_d(ln)),
            i64_from(rint_d(rn))));
        break;
    case 34:
        rn
            = i64_to
            (
            i64_not(i64_xor(i64_from(rint_d(ln)),
            i64_from(rint_d(rn)))));
        break;
    case 35:
        rn
            = i64_to(i64_or(i64_not(i64_from(rint_d(ln))),
            i64_from(rint_d(rn))));
        break;
    case 37:
    case 38:
        x = rint_d(ln);
        y = rint_d(rn);
        if (y < 0.0 || y > 63.0) {
            if (k == 37) rn = 0.0;
            else if (x < 0.0) rn = -1.0;
            else rn = 0.0;
        } else {
            a = i64_from(x);
            b = a;
            for (sh = 0; sh < (long)y; sh++) b = (k == 37)
                ? i64_shl1(b) : i64_sar1(b);
            rn = i64_to(b);
        }
        break;
    default:
        syn();
        break;
    }
    rt = 0;
}

/* identifier: variable, array element, builtin or user function */
static void ex_id(void)
{
    long slot, idx, j, base, na, r;
    slot = tk[pc].k;
    if (tk[pc].f > 0) {
        if (tk[pc].y == 0) tk[pc].y = find_proc(tk[pc].s) + 1;
        if (tk[pc].y == 1) {
            do_builtin();
            return;
        }
        j = tk[pc].y - 1;
        pc++;
        base = ab_cnt;
        na = 0;
        if (tk[pc].t == 5 && tk[pc].k == 7) na = eval_args(j);
        if (err_flag == 1) {
            ab_cnt = base;
            return;
        }
        invoke(j, base, na);
        return;
    }
    if (tk[pc].x == 0) {
        /* a user function with no argument list? */
        j = tk[pc].y;
        if (j == 0) {
            if (tk[pc].sl > 2 && tk[pc].s[0] == 'F'
                && tk[pc].s[1] == 'N') j = 0 - find_fn(tk[pc].s);
            if (j == 0) j = BIGKIND;
            tk[pc].y = j;
        }
        if (j < 0) {
            call_fn(0 - j);
            return;
        }
        if (vars[slot].kind == 2) {
            s_cpy(&rs, &vars[slot].s);
            rt = 1;
        } else {
            rn = vars[slot].n;
            rt = 0;
        }
        pc++;
        return;
    }
    /* followed by '(' */
    if (vars[slot].isarr == 1) {
        pc++;
        idx = arr_index(slot);
        if (err_flag == 1) return;
        if (vars[slot].kind == 2) {
            s_cpy(&rs, &pool_s[idx]);
            rt = 1;
        } else {
            rn = pool_n[idx];
            rt = 0;
        }
        return;
    }
    r = tk[pc].y;
    if (r == 0) {
        r = find_proc(tk[pc].s);
        if (r == 0) {
            j = find_fn(tk[pc].s);
            if (j > 0) r = -j;
        }
        if (r == 0) r = BIGKIND;
        tk[pc].y = r;
    }
    if (r > 0 && r < BIGKIND) {
        pc++;
        base = ab_cnt;
        na = eval_args(r);
        if (err_flag == 1) {
            ab_cnt = base;
            return;
        }
        invoke(r, base, na);
        return;
    }
    if (r < 0) {
        call_fn(-r);
        return;
    }
    /* implicit array */
    pc++;
    idx = arr_index(slot);
    if (err_flag == 1) return;
    if (vars[slot].kind == 2) {
        s_cpy(&rs, &pool_s[idx]);
        rt = 1;
    } else {
        rn = pool_n[idx];
        rt = 0;
    }
}

/* ---------- argument lists and procedure calls ---------- */
/* pc is at '('; evaluate the arguments onto the argument stack;
   returns count */
static long eval_args(long p)
{
    long n0, sv, pc2, idx;
    ArgEnt *a;
    n0 = 0;
    if (bare_flag == 0) {
        pc++;
        if (tk[pc].t == 5 && tk[pc].k == 8) {
            pc++;
            return 0;
        }
    }
    for (;;) {
        if (tk[pc].t == 5 && tk[pc].k == 18) pc++;
        sv = pc;
        if (tk[sv].t == 3 && tk[sv].f == 0 && tk[sv].x == 1
            && tk[sv + 1].t == 5 && tk[sv + 1].k == 7 &&
            tk[sv + 2].t == 5 && tk[sv + 2].k == 8) {
            /* whole array: name() */
            ab_cnt++;
            NEED(argstk, ab_cap, ab_cnt + 2);
            a = &argstk[ab_cnt];
            a->n = 0.0;
            s_clr(&a->s);
            a->t = 2;
            a->slot = tk[sv].k;
            a->idx = 0;
            pc = sv + 3;
        } else {
            ex_prec(1);
            if (err_flag == 1) return n0;
            ab_cnt++;
            NEED(argstk, ab_cap, ab_cnt + 2);
            a = &argstk[ab_cnt];
            a->n = rn;
            s_cpy(&a->s, &rs);
            a->t = rt;
            a->slot = 0;
            a->idx = 0;
            if (p > 0 && n0 < procs[p].pcnt) {
                if (pparms[procs[p].pfirst + n0].ref == 1
                    && tk[sv].t == 3 && tk[sv].f == 0) {
                    if (tk[sv].x == 0 && pc == sv + 1)
                        argstk[ab_cnt].slot = tk[sv].k;
                    else if (tk[sv].x == 1
                        && vars[tk[sv].k].isarr == 1) {
                        long cur;
                        cur = ab_cnt;
                        pc2 = pc;
                        pc = sv + 1;
                        idx = arr_index(tk[sv].k);
                        if (pc == pc2 && err_flag == 0) {
                            argstk[cur].slot = 0 - tk[sv].k;
                            argstk[cur].idx = idx;
                        }
                        pc = pc2;
                    }
                }
            }
        }
        n0++;
        if (tk[pc].t == 5 && tk[pc].k == 9) pc++;
        else break;
    }
    if (bare_flag == 0) need_rparen();
    return n0;
}

static void swap_str(Str *a, Str *b)
{
    Str t;
    t = *a;
    *a = *b;
    *b = t;
}

/* call a SUB / FUNCTION: arguments are on the argument stack from
   base+1 */
static void invoke(long p, long base, long na)
{
    long first, cnt, npar, pf, i, d, s, a, r, src, save_pc, sv0;
    Proc *pr;
    SvEnt *sv;
    Var *v;
    if (cfp > 400) {
        rt_error(7, "Out of memory (recursion too deep)");
        ab_cnt = base;
        return;
    }
    pr = &procs[p];
    first = pr->first;
    cnt = pr->cnt;
    npar = pr->pcnt;
    pf = pr->pfirst;
    save_pc = pc;
    sv0 = svp;
    /* save and reset the locals */
    for (i = 0; i < cnt; i++) {
        s = pl_slots[first + i];
        svp++;
        NEED(svstack, svstack_cap, svp + 2);
        sv = &svstack[svp];
        v = &vars[s];
        sv->n = v->n;
        swap_str(&sv->s, &v->s);
        sv->base = v->base;
        sv->isarr = v->isarr;
        sv->nd = v->nd;
        for (d = 0; d < 3; d++) {
            sv->lo[d] = v->lo[d];
            sv->hi[d] = v->hi[d];
        }
        v->n = 0.0;
        s_clr(&v->s);
        v->isarr = 0;
        v->nd = 0;
        v->base = 0;
    }
    /* bind the parameters */
    for (i = 1; i <= npar; i++) {
        s = pparms[pf + i - 1].slot;
        if (i <= na) {
            a = base + i;
            if (pparms[pf + i - 1].arr == 1) {
                if (argstk[a].t == 2) {
                    src = argstk[a].slot;
                    vars[s].base = vars[src].base;
                    vars[s].isarr = vars[src].isarr;
                    vars[s].nd = vars[src].nd;
                    for (d = 0; d < 3; d++) {
                        vars[s].lo[d] = vars[src].lo[d];
                        vars[s].hi[d] = vars[src].hi[d];
                    }
                } else rt_error(13, "Type mismatch");
            } else if (vars[s].kind == 2) {
                if (argstk[a].t == 1) s_cpy(&vars[s].s, &argstk[a].s);
                else rt_error(13, "Type mismatch");
            } else {
                if (argstk[a].t == 0) {
                    if (vars[s].kind == 1)
                        vars[s].n = rint_d(argstk[a].n);
                    else vars[s].n = argstk[a].n;
                } else rt_error(13, "Type mismatch");
            }
        }
    }
    if (err_flag == 0) {
        cfp++;
        NEED(cf_gsp, cf_cap, cfp + 2);
        NEED(cf_proc, cf_pcap, cfp + 2);
        cf_gsp[cfp] = gsp;
        cf_proc[cfp] = p;
        retflag = 0;
        pc = pr->body;
        run_loop();
        cfp--;
        /* result of a FUNCTION */
        if (pr->isfn == 1) {
            r = pr->ret;
            if (vars[r].kind == 2) {
                s_cpy(&rs, &vars[r].s);
                rt = 1;
            } else {
                rn = vars[r].n;
                rt = 0;
            }
        } else {
            rn = 0.0;
            rt = 0;
        }
        /* copy BYREF parameters back */
        for (i = 1; i <= npar; i++) {
            if (i <= na) {
                a = base + i;
                s = pparms[pf + i - 1].slot;
                if (pparms[pf + i - 1].ref == 1
                    && pparms[pf + i - 1].arr == 0) {
                    if (argstk[a].slot > 0) {
                        if (vars[argstk[a].slot].kind == 2)
                            s_cpy(&vars[argstk[a].slot].s, &vars[s].s);
                        else vars[argstk[a].slot].n = vars[s].n;
                    } else if (argstk[a].slot < 0 && argstk[a].idx > 0)
                        {
                        if (vars[0 - argstk[a].slot].kind == 2)
                            s_cpy(&pool_s[argstk[a].idx], &vars[s].s);
                        else pool_n[argstk[a].idx] = vars[s].n;
                    }
                }
            }
        }
    }
    /* restore the locals */
    for (i = cnt - 1; i >= 0; i--) {
        s = pl_slots[first + i];
        sv = &svstack[svp];
        v = &vars[s];
        v->n = sv->n;
        swap_str(&sv->s, &v->s);
        v->base = sv->base;
        v->isarr = sv->isarr;
        v->nd = sv->nd;
        for (d = 0; d < 3; d++) {
            v->lo[d] = sv->lo[d];
            v->hi[d] = sv->hi[d];
        }
        svp--;
    }
    svp = sv0;
    ab_cnt = base;
    pc = save_pc;
    retflag = 0;
}

/* DEF FN user function: pc is at the FN name token */
static void call_fn(long j)
{
    long q, base, na, i, np0, s, e0, save_pc, sv0;
    long pcs[256];
    q = fns_def[j].pc;
    np0 = 0;
    if (tk[q].t == 5 && tk[q].k == 7) {
        q++;
        while (tk[q].t != 6 && tk[q].t != 7) {
            if (tk[q].t == 5 && tk[q].k == 8) break;
            if (tk[q].t == 3 && np0 < 255) {
                np0++;
                pcs[np0] = tk[q].k;
            }
            q++;
        }
        q++;
    }
    e0 = q + 1;
    pc++;
    base = ab_cnt;
    na = 0;
    if (tk[pc].t == 5 && tk[pc].k == 7) na = eval_args(0);
    if (err_flag == 1) {
        ab_cnt = base;
        return;
    }
    if (na != np0) {
        rt_error(5, "Illegal function call");
        ab_cnt = base;
        return;
    }
    save_pc = pc;
    sv0 = svp;
    for (i = 1; i <= np0; i++) {
        s = pcs[i];
        svp++;
        NEED(svstack, svstack_cap, svp + 2);
        svstack[svp].n = vars[s].n;
        swap_str(&svstack[svp].s, &vars[s].s);
        s_clr(&vars[s].s);
        if (vars[s].kind == 2) {
            if (argstk[base + i].t == 1)
                s_cpy(&vars[s].s, &argstk[base + i].s);
            else rt_error(13, "Type mismatch");
        } else {
            if (argstk[base + i].t == 0)
                vars[s].n = argstk[base + i].n;
            else rt_error(13, "Type mismatch");
        }
    }
    ab_cnt = base;
    pc = e0;
    ex_prec(1);
    for (i = np0; i >= 1; i--) {
        s = pcs[i];
        vars[s].n = svstack[svp].n;
        swap_str(&svstack[svp].s, &vars[s].s);
        svp--;
    }
    svp = sv0;
    pc = save_pc;
}

